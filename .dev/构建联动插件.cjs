const fs=require('fs'),path=require('path');
const folder=path.resolve(__dirname,'../.obsidian/plugins/light-okr');
// Obsidian executes main.js as one module. Keep vault-local modules inside it;
// only the host's Obsidian API is required from the external environment.
function bundle(){
  const names=['core','dashboard','plugin'];
  const definitions=names.map(name=>JSON.stringify('./'+name)+':function(module,exports,require){\n'+fs.readFileSync(path.join(folder,name+'.js'),'utf8').trimEnd()+'\n}').join(',\n');
  return '// Generated by .dev/构建联动插件.cjs; edit core/dashboard/plugin.js.\n'+
    'module.exports=(()=>{\nconst definitions={\n'+definitions+'\n};\n'+
    'const cache=Object.create(null);\n'+
    'function load(id){\n'+
    '  if(!Object.prototype.hasOwnProperty.call(definitions,id))return require(id);\n'+
    '  if(cache[id])return cache[id].exports;\n'+
    '  const module={exports:{}};cache[id]=module;\n'+
    '  definitions[id](module,module.exports,load);return module.exports;\n'+
    '}\nreturn load("./plugin");\n})();\n';
}
if(require.main===module){const output=bundle();fs.writeFileSync(path.join(folder,'main.js'),output);console.log('Built self-contained light-okr/main.js ('+Buffer.byteLength(output)+' bytes)');}
module.exports={bundle};
